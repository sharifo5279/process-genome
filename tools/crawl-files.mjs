// Writes site/robots.txt and site/sitemap.xml so search engines and AI agents (Google, Bing and the assistants that
// search through Bing, such as Copilot) can find every page and agent file. Runs at the end of tools/build-site.mjs and
// tools/command-center/apply.py; run it by hand after any other change under site/:
//   node tools/crawl-files.mjs           update robots.txt, sitemap.xml and tools/crawl-state.json
//   node tools/crawl-files.mjs --check   exit 1 if they are out of date (npm test runs this)
// lastmod is the UTC date a file's content last changed, kept in tools/crawl-state.json (path -> sha256 + date), so it
// stays correct in shallow clones and only moves when the content does.
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SITE_DIR = path.join(ROOT, "site");
const STATE = path.join(ROOT, "tools/crawl-state.json");
export const ORIGIN = "https://process-genome.onrender.com";

// Pages (every index.html except the stats page) and the agent-readable files. Images, scripts and favicons stay out.
export function crawlable(siteDir = SITE_DIR) {
  const out = [];
  (function walk(rel) {
    for (const e of fs.readdirSync(path.join(siteDir, rel), { withFileTypes: true })) {
      const p = rel ? rel + "/" + e.name : e.name;
      if (e.isDirectory()) { if (p !== "stats") walk(p); continue; }
      if (e.name === "index.html" || p === "llms.txt" || p === "llms-full.txt" || /^agents\/[^/]+\.txt$/.test(p)) out.push(p);
    }
  })("");
  return out.sort((a, b) => (urlOf(a).length - urlOf(b).length) || (a < b ? -1 : 1));
}
export const urlOf = (p) => ORIGIN + "/" + p.replace(/(^|\/)index\.html$/, "$1");
const sha = (f) => crypto.createHash("sha256").update(fs.readFileSync(f)).digest("hex");

export function robots() {
  return [
    "# Business Network Process Genome. Generated by tools/crawl-files.mjs; do not hand-edit.",
    "# Agent-readable files: " + ORIGIN + "/llms.txt",
    "User-agent: *",
    "Allow: /",
    "Disallow: /stats/",
    "",
    "Sitemap: " + ORIGIN + "/sitemap.xml",
    "",
  ].join("\n");
}

export function sitemap(state, files) {
  const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;");
  return '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' +
    files.map((p) => `  <url><loc>${esc(urlOf(p))}</loc><lastmod>${state[p].lastmod}</lastmod></url>\n`).join("") + "</urlset>\n";
}

// Returns the list of problems (empty = up to date). With write, brings everything up to date instead.
export function run({ write = false, today = new Date().toISOString().slice(0, 10) } = {}) {
  const files = crawlable();
  const old = fs.existsSync(STATE) ? JSON.parse(fs.readFileSync(STATE, "utf8")) : {};
  const state = {}, problems = [];
  for (const p of files) {
    const h = sha(path.join(SITE_DIR, p));
    if (old[p] && old[p].sha256 === h) state[p] = old[p];
    else { state[p] = { sha256: h, lastmod: today }; problems.push((old[p] ? "changed " : "new ") + p); }
  }
  for (const p of Object.keys(old)) if (!state[p]) problems.push("removed " + p);
  const want = { "robots.txt": robots(), "sitemap.xml": sitemap(state, files) };
  for (const [f, text] of Object.entries(want)) {
    const at = path.join(SITE_DIR, f);
    if (!fs.existsSync(at) || fs.readFileSync(at, "utf8") !== text) problems.push("stale site/" + f);
  }
  if (write) {
    for (const [f, text] of Object.entries(want)) fs.writeFileSync(path.join(SITE_DIR, f), text);
    fs.writeFileSync(STATE, JSON.stringify(state, null, 1) + "\n");
  }
  return { problems, files };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes("--check")) {
    const { problems } = run();
    if (problems.length) { console.error("crawl files out of date (run node tools/crawl-files.mjs):\n  " + problems.join("\n  ")); process.exit(1); }
    console.log("crawl files up to date");
  } else {
    const { problems, files } = run({ write: true });
    console.log(`crawl files: ${files.length} URLs in site/sitemap.xml` + (problems.length ? "; " + problems.join(", ") : "; no changes"));
  }
}
